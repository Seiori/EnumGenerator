namespace Seiori.EnumGenerator;

internal static class AttributeSource
{
    public const string Namespace = "Seiori.EnumGenerator";

    public const string MetadataName = Namespace + ".EnumExtensionsAttribute";

    /// <summary>Per-member attribute: the text <c>GetDisplayValue()</c> returns.</summary>
    public const string DisplayAttributeName = "EnumDisplayAttribute";

    /// <summary>Per-member attribute: the text <c>GetDescription()</c> returns.</summary>
    public const string DescriptionAttributeName = "EnumDescriptionAttribute";

    /// <summary>Per-member attribute: the name used in JSON and by <c>GetEnumMemberValue()</c>.</summary>
    public const string JsonAttributeName = "EnumJsonAttribute";

    public const string HintName = "Seiori.EnumGenerator.Attributes.g.cs";

    // Must compile under C# 7.3 and without nullable annotations: post-initialization output cannot see the
    // consumer's language version. [Conditional] keeps the attributes out of the consumer's compiled metadata.
    public const string Source = """
        // <auto-generated/>
        #if !SEIORI_ENUMGENERATOR_EXCLUDE_ATTRIBUTE
        namespace Seiori.EnumGenerator
        {
            /// <summary>
            /// Generates fast, allocation-free extension methods (and a System.Text.Json converter) for the annotated enum.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Enum, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SEIORI_ENUMGENERATOR_USAGES")]
            internal sealed class EnumExtensionsAttribute : global::System.Attribute
            {
                /// <summary>
                /// The name of the generated static class. Defaults to <c>{EnumName}Extensions</c>
                /// (prefixed with the containing type names for nested enums).
                /// </summary>
                public string ExtensionClassName { get; set; }

                /// <summary>The namespace of the generated static class. Defaults to the enum's namespace.</summary>
                public string ExtensionClassNamespace { get; set; }
            }

            /// <summary>
            /// The name shown to people for this enum member: what the generated <c>GetDisplayValue()</c> returns.
            /// Takes priority over <c>[Display(Name)]</c>.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SEIORI_ENUMGENERATOR_USAGES")]
            internal sealed class EnumDisplayAttribute : global::System.Attribute
            {
                /// <summary>Creates the attribute.</summary>
                /// <param name="text">The display text.</param>
                public EnumDisplayAttribute(string text)
                {
                    Text = text;
                }

                /// <summary>The display text.</summary>
                public string Text { get; }
            }

            /// <summary>
            /// What this enum member is or does: what the generated <c>GetDescription()</c> returns.
            /// Takes priority over <c>[Display(Description)]</c> and <c>[Description]</c>.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SEIORI_ENUMGENERATOR_USAGES")]
            internal sealed class EnumDescriptionAttribute : global::System.Attribute
            {
                /// <summary>Creates the attribute.</summary>
                /// <param name="text">The description.</param>
                public EnumDescriptionAttribute(string text)
                {
                    Text = text;
                }

                /// <summary>The description.</summary>
                public string Text { get; }
            }

            /// <summary>
            /// The name of this enum member in JSON: what the generated converter writes and reads, and what
            /// <c>GetEnumMemberValue()</c> and <c>TryParseEnumMemberValue</c> use. Takes priority over
            /// <c>[JsonStringEnumMemberName]</c>, <c>[EnumMember(Value)]</c> and <c>[JsonPropertyName]</c>.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = false, Inherited = false)]
            [global::System.Diagnostics.Conditional("SEIORI_ENUMGENERATOR_USAGES")]
            internal sealed class EnumJsonAttribute : global::System.Attribute
            {
                /// <summary>Creates the attribute.</summary>
                /// <param name="name">The name written to and read from JSON.</param>
                public EnumJsonAttribute(string name)
                {
                    Name = name;
                }

                /// <summary>The name written to and read from JSON.</summary>
                public string Name { get; }
            }
        }
        #endif

        """;
}
